// Command flower-turn-contract generates the consumer's turn kinds from the
// public Go types of the published Floret module selected by go.mod.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/constant"
	"go/importer"
	"go/token"
	"go/types"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
)

const runtimePackage = "github.com/floegence/floret/v7/runtime"

func publishedRuntime(root string) (*types.Package, error) {
	cmd := exec.Command("go", "list", "-mod=readonly", "-deps", "-export", "-json", runtimePackage)
	cmd.Dir = root
	cmd.Env = append(os.Environ(), "GOWORK=off")
	raw, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("load published Floret export data: %w", err)
	}
	exports := map[string]string{}
	dec := json.NewDecoder(bytes.NewReader(raw))
	for {
		var pkg struct {
			ImportPath, Export string
			Module             *struct {
				Version string
				Replace json.RawMessage
			}
		}
		if err := dec.Decode(&pkg); err == io.EOF {
			break
		} else if err != nil {
			return nil, err
		}
		if pkg.ImportPath == runtimePackage && (pkg.Module == nil || pkg.Module.Version == "" || len(pkg.Module.Replace) != 0) {
			return nil, fmt.Errorf("Floret must resolve to a published version without replacement")
		}
		exports[pkg.ImportPath] = pkg.Export
	}
	return importer.ForCompiler(token.NewFileSet(), "gc", func(path string) (io.ReadCloser, error) {
		file := exports[path]
		if file == "" {
			return nil, fmt.Errorf("missing export data for %s", path)
		}
		return os.Open(file)
	}).Import(runtimePackage)
}

func turnKinds(pkg *types.Package) ([]string, error) {
	obj := pkg.Scope().Lookup("TurnKind")
	if obj == nil {
		return nil, fmt.Errorf("published runtime.TurnKind is missing")
	}
	seen := map[string]bool{}
	for _, name := range pkg.Scope().Names() {
		c, ok := pkg.Scope().Lookup(name).(*types.Const)
		if !ok || !c.Exported() || !types.Identical(c.Type(), obj.Type()) {
			continue
		}
		if c.Val().Kind() != constant.String {
			return nil, fmt.Errorf("%s is not a string constant", name)
		}
		value := constant.StringVal(c.Val())
		if value != "" {
			seen[value] = true
		}
	}
	if len(seen) == 0 {
		return nil, fmt.Errorf("published runtime.TurnKind has no exported values")
	}
	values := make([]string, 0, len(seen))
	for value := range seen {
		values = append(values, value)
	}
	sort.Strings(values)
	return values, nil
}

func render(kinds []string) []byte {
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Generated by go run ./internal/cmd/flower-turn-contract. Do not edit.")
	fmt.Fprintln(&out, "// Source: the published Floret runtime.TurnKind constants selected by go.mod.")
	fmt.Fprintln(&out, "export const FLOWER_TURN_KINDS = [")
	for _, kind := range kinds {
		fmt.Fprintf(&out, "  %s,\n", strconv.Quote(kind))
	}
	fmt.Fprintln(&out, "] as const;")
	fmt.Fprintln(&out, "export type FlowerTurnKind = typeof FLOWER_TURN_KINDS[number];")
	fmt.Fprintln(&out, "\nexport function isFlowerTurnKind(value: unknown): value is FlowerTurnKind {")
	fmt.Fprintln(&out, "  return FLOWER_TURN_KINDS.some(kind => kind === value);")
	fmt.Fprintln(&out, "}")
	return out.Bytes()
}

func run(root string, check bool) error {
	pkg, err := publishedRuntime(root)
	if err != nil {
		return err
	}
	kinds, err := turnKinds(pkg)
	if err != nil {
		return err
	}
	output := render(kinds)
	path := filepath.Join(root, "internal/flower_ui/src/contracts/flowerTurnKind.generated.ts")
	if check {
		current, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, output) {
			return fmt.Errorf("Flower turn kinds differ from the published Floret API; run go run ./internal/cmd/flower-turn-contract and qualify every kind")
		}
	} else if err := os.WriteFile(path, output, 0644); err != nil {
		return err
	}
	fmt.Printf("Flower turn kinds verified against published Floret (%d kinds)\n", len(kinds))
	return nil
}

func main() {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "verify the committed generated contract")
	flag.Parse()
	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
