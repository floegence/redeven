  await expect(restored.locator('[data-terminal-vacant-slot]:visible')).toHaveCount(2);
  report.checks.push('closing all sessions retains every slot across browsers and reload, and creation recovers in place');
  const sessionCountBeforeDelete = await emptyRestored.locator('[data-terminal-session-id]').count();
  await emptyRestored.getByRole('button', { name: 'Actions for Logs', exact: true }).click();
  await other.page.getByRole('menuitem', { name: 'Delete view', exact: true }).click();
