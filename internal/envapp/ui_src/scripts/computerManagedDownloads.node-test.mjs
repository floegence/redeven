import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { observeManagedBrowserDownloads } from './computerManagedDownloads.mjs';

test('managed file handles share native state and reject substitution, cancellation and disposal', async t => {
  const directory = await mkdtemp(path.join(tmpdir(), 'redeven-managed-download-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const id = '12345678-1234-1234-1234-123456789abc', filename = path.join(directory, id);
  const bytes = Buffer.from('Original native download');
  await writeFile(filename, bytes);
  const record = { id, filename: 'report.txt', state: 'in_progress', received_bytes: 0 };
  const page = { downloads: new Map([[id, record]]), listeners: new Set() };
  const files = [], commands = [], subscriptions = [];
  const source = { downloads: () => files, reportDownload(download) { files.push(download); }, transport: { async send(method, parameters) { commands.push({ method, parameters }); } } };
  const close = observeManagedBrowserDownloads(source, page, directory);
  t.after(() => { subscriptions.forEach(unsubscribe => unsubscribe()); close(); });
  assert.equal(files.length, 1);
  const download = files[0];
  let changes = 0;
  subscriptions.push(download.subscribe(() => changes++));
  await download.cancel();
  assert.deepEqual(commands, [{ method: 'Browser.cancelDownload', parameters: { guid: id } }]);
  await assert.rejects(download.open(new AbortController().signal), /UNAVAILABLE/u);
  Object.assign(record, { state: 'completed', path: filename, size_bytes: bytes.length, received_bytes: bytes.length });
  for (const listener of page.listeners) listener();
  assert.equal(changes, 1);
  assert.equal(files.length, 1, 'Native progress does not duplicate handles');
  assert.equal(download.state.status, 'complete');
  const chunks = [];
  for await (const chunk of await download.open(new AbortController().signal)) chunks.push(chunk);
  assert.deepEqual(Buffer.concat(chunks), bytes);
  await download.cancel();
  assert.equal(commands.length, 1, 'Completed native downloads are never canceled');
  const abort = new AbortController(); abort.abort();
  await assert.rejects(download.open(abort.signal), { name: 'AbortError' });
  await rm(filename);
  const unrelated = path.join(directory, 'unrelated');
  await writeFile(unrelated, bytes);
  await symlink(unrelated, filename);
  await assert.rejects(download.open(new AbortController().signal));
  assert.deepEqual(await readFile(unrelated), bytes, 'Rejecting a substituted handle leaves unrelated files intact');
  await rm(filename); await writeFile(filename, 'different size');
  await assert.rejects(download.open(new AbortController().signal), /UNAVAILABLE/u);
  await writeFile(filename, bytes);
  close();
  await assert.rejects(download.open(new AbortController().signal), /UNAVAILABLE/u);
});
