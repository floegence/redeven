import '../index.css';
import './flower-feature.css';
import { createSignal } from 'solid-js';
import { expect, it, vi } from 'vitest';
import { page } from 'vitest/browser';
import type { FlowerSettingsSnapshot, FlowerSubagentDetail } from '../../../../flower_ui/src/contracts/flowerSurfaceContracts';
import { withModelDirectoryFixture } from '../../../../flower_ui/testing/modelDirectoryFixture';
import { adapter, deferred, liveBootstrap, renderSurfaceWithAdapterProps, settingsSnapshot, subagentSummary, thread, waitFor } from './FlowerSurface.navigation.testHarness';

const frames = () => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve())));
it.each([1280, 390])('floats settings loading and recovery without resizing a new chat at %i pixels', async width => {
  await page.viewport(width, 900);
  const pending = deferred<FlowerSettingsSnapshot>();
  const retry = deferred<FlowerSettingsSnapshot>();
  const loadSettings = vi.fn().mockResolvedValueOnce(settingsSnapshot()).mockImplementationOnce(() => pending.promise).mockImplementationOnce(() => retry.promise);
  const [revision, setRevision] = createSignal(0);
  const root = renderSurfaceWithAdapterProps({ ...adapter(), loadSettings, loadModelDirectory: async () => withModelDirectoryFixture(settingsSnapshot()).model_directory! }, { settingsRevision: revision });
  root.style.cssText = `height:780px;width:${width}px`;
  await waitFor(() => Boolean(root.querySelector('.flower-empty-state')) && !root.querySelector('.flower-settings-read-status'));
  await frames();
  const viewport = root.querySelector<HTMLElement>('.flower-chat-transcript')!;
  const editor = root.querySelector<HTMLTextAreaElement>('textarea')!;
  editor.value = 'Keep this draft'; editor.dispatchEvent(new InputEvent('input', { bubbles: true })); editor.focus();
  const bounds = viewport.getBoundingClientRect();
  const top = editor.getBoundingClientRect().top;
  const verifyGeometry = () => {
    expect(Math.abs(viewport.getBoundingClientRect().top - bounds.top)).toBeLessThanOrEqual(1);
    expect(Math.abs(viewport.getBoundingClientRect().height - bounds.height)).toBeLessThanOrEqual(1);
    expect(Math.abs(editor.getBoundingClientRect().top - top)).toBeLessThanOrEqual(1);
    expect(root.querySelector('textarea')).toBe(editor);
    expect(editor.value).toBe('Keep this draft');
  };
  setRevision(1);
  await waitFor(() => loadSettings.mock.calls.length === 2);
  await frames(); verifyGeometry();
  const status = () => root.querySelector<HTMLElement>('.flower-settings-read-status')!;
  expect(status().closest('.flower-chat-notices')).not.toBeNull();
  expect(status().querySelectorAll('.flower-thread-wave-bar')).toHaveLength(4);
  expect(getComputedStyle(root.querySelector('.flower-chat-notices')!).pointerEvents).toBe('none');
  expect(getComputedStyle(status()).pointerEvents).toBe('auto');
  expect(document.activeElement).toBe(editor);
  pending.reject(new Error('Settings unavailable'));
  await waitFor(() => status()?.getAttribute('role') === 'alert');
  await frames(); verifyGeometry();
  expect(status().querySelector('.flower-thread-wave')).toBeNull();
  expect(status().textContent).toContain('Settings unavailable');
  expect(root.scrollWidth).toBeLessThanOrEqual(root.clientWidth + 1);
  await page.screenshot({ element: root, path: `__screenshots__/flower-floating-error-${width}.png` });
  status().querySelector<HTMLButtonElement>('button')!.click();
  await waitFor(() => loadSettings.mock.calls.length === 3);
  retry.resolve(settingsSnapshot());
  await waitFor(() => !status());
  await frames(); verifyGeometry();
});

it('keeps settings recovery floating and clickable above a collapsed companion', async () => {
  await page.viewport(800, 700);
  const loadSettings = vi.fn().mockRejectedValueOnce(new Error('Settings unavailable')).mockResolvedValue(settingsSnapshot());
  const root = renderSurfaceWithAdapterProps({ ...adapter(), loadSettings, loadModelDirectory: async () => withModelDirectoryFixture(settingsSnapshot()).model_directory! }, { presentation: 'companion', companionOpen: false, engaged: true });
  root.style.cssText = 'position:absolute;top:300px;width:600px;height:32px';
  await waitFor(() => Boolean(root.querySelector('.flower-settings-read-status button')));
  await frames();
  const composer = root.querySelector<HTMLElement>('.flower-composer')!;
  const notice = root.querySelector<HTMLElement>('.flower-settings-read-status')!;
  const retry = notice.querySelector<HTMLButtonElement>('button')!;
  const rect = retry.getBoundingClientRect();
  expect(rect.bottom).toBeLessThanOrEqual(composer.getBoundingClientRect().top);
  expect(retry.contains(document.elementFromPoint(rect.left + rect.width / 2, rect.top + rect.height / 2))).toBe(true);
  expect(composer.getBoundingClientRect().height).toBe(32);
  retry.click();
  await waitFor(() => !root.querySelector('.flower-settings-read-status'));
  expect(composer.getBoundingClientRect().height).toBe(32);
});

it('keeps child loading and retry in the same floating stack without resizing its reading region', async () => {
  await page.viewport(1280, 900);
  const child = subagentSummary();
  const parent = thread({ thread_id: child.parent_thread_id, subagents: [child] });
  const pending = deferred<FlowerSubagentDetail>();
  const retry = deferred<FlowerSubagentDetail>();
  const loadSubagentDetail = vi.fn().mockImplementationOnce(() => pending.promise).mockImplementationOnce(() => retry.promise);
  const root = renderSurfaceWithAdapterProps({ ...adapter(), listThreads: async () => [parent], loadThread: async () => liveBootstrap(parent), loadSubagentDetail }, { focusThreadRequest: { request_id: 'floating-child', thread_id: parent.thread_id } });
  root.style.height = '780px';
  await waitFor(() => Boolean(root.querySelector('button[aria-controls="flower-subagents-dropdown"]')));
  root.querySelector<HTMLButtonElement>('button[aria-controls="flower-subagents-dropdown"]')!.click();
  await waitFor(() => Boolean(document.querySelector('[data-flower-subagent-row]')));
  document.querySelector<HTMLButtonElement>('[data-flower-subagent-row]')!.click();
  await waitFor(() => Boolean(document.querySelector('.flower-subagent-detail-loading')));
  const window = document.querySelector<HTMLElement>('.flower-subagent-detail-window')!;
  await frames();
  await Promise.all(window.getAnimations().map(animation => animation.finished));
  // The window positions its floating shell after its first layout.
  await new Promise(resolve => setTimeout(resolve, 350));
  const region = window.querySelector<HTMLElement>('.flower-subagent-detail-transcript-region')!;
  const before = region.getBoundingClientRect();
  const loading = window.querySelector<HTMLElement>('.flower-subagent-detail-loading')!;
  expect(loading.closest('.flower-chat-notices')).not.toBeNull();
  expect(loading.querySelectorAll('.flower-thread-wave-bar')).toHaveLength(4);
  pending.reject(new Error('Child conversation unavailable'));
  await waitFor(() => Boolean(window.querySelector('.flower-subagent-detail-state-error')));
  await frames();
  expect(Math.abs(region.getBoundingClientRect().top - before.top)).toBeLessThanOrEqual(1);
  expect(Math.abs(region.getBoundingClientRect().height - before.height)).toBeLessThanOrEqual(1);
  const error = window.querySelector<HTMLElement>('.flower-subagent-detail-state-error')!;
  expect(error.closest('.flower-chat-notices')).not.toBeNull();
  expect(error.querySelector('.flower-thread-wave')).toBeNull();
  error.querySelector<HTMLButtonElement>('button')!.click();
  await waitFor(() => loadSubagentDetail.mock.calls.length === 2 && Boolean(window.querySelector('.flower-subagent-detail-loading')));
  expect(window.querySelector('.flower-subagent-detail-state-error')).toBeNull();
  retry.reject(new Error('Child conversation still unavailable'));
  await waitFor(() => Boolean(window.querySelector('.flower-subagent-detail-state-error button')));
  expect(loadSubagentDetail).toHaveBeenCalledTimes(2);
  expect(window.querySelector('.flower-subagent-detail-loading')).toBeNull();
  expect(Math.abs(region.getBoundingClientRect().height - before.height)).toBeLessThanOrEqual(1);
});
