export function automationText(locale: RedevenLocale, key: string): string {
  let value: unknown = automationMessages[locale];
  for (const part of key.split("."))
    value = (value as Record<string, unknown>)?.[part];
  if (typeof value !== "string")
    throw new Error(`Missing automation message: ${locale}/${key}`);
  return value;
}
