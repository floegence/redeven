// Command center-contracts generates browser DTOs and JSON Schema from Go's public contracts.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"github.com/floegence/redeven/internal/environmentcenter"
	"os"
	"reflect"
	"sort"
	"strconv"
	"strings"
)

type generated struct {
	ts     string
	schema map[string]any
}

func contract(t reflect.Type) generated {
	if t.Kind() == reflect.Pointer {
		return contract(t.Elem())
	}
	switch t.Kind() {
	case reflect.String:
		return generated{"string", map[string]any{"type": "string"}}
	case reflect.Bool:
		return generated{"boolean", map[string]any{"type": "boolean"}}
	case reflect.Int, reflect.Int64, reflect.Uint, reflect.Uint64, reflect.Uint32:
		minimum := int64(-9007199254740991)
		if t.Kind() == reflect.Uint || t.Kind() == reflect.Uint64 || t.Kind() == reflect.Uint32 {
			minimum = 0
		}
		return generated{"number", map[string]any{"type": "integer", "minimum": minimum, "maximum": int64(9007199254740991)}}
	case reflect.Slice, reflect.Array:
		v := contract(t.Elem())
		return generated{"(" + v.ts + ")[]", map[string]any{"type": "array", "items": v.schema}}
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			panic("non-string public map")
		}
		v := contract(t.Elem())
		return generated{"Record<string, " + v.ts + ">", map[string]any{"type": "object", "additionalProperties": v.schema}}
	case reflect.Struct:
		parts := []string{}
		required := []string{}
		properties := map[string]any{}
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			tag := strings.Split(f.Tag.Get("json"), ",")
			if !f.IsExported() || tag[0] == "-" {
				continue
			}
			name := tag[0]
			if name == "" {
				name = f.Name
			}
			optional := strings.Contains(f.Tag.Get("json"), ",omitempty")
			v := contract(f.Type)
			if values := f.Tag.Get("enum"); values != "" {
				if f.Type.Kind() != reflect.String {
					panic("enum requires a string field")
				}
				enumerated := strings.Split(values, ",")
				literals := make([]string, len(enumerated))
				for index, value := range enumerated {
					literals[index] = strconv.Quote(value)
				}
				v.ts, v.schema["enum"] = strings.Join(literals, " | "), enumerated
			}
			for _, bound := range []string{"minimum", "maximum"} {
				if raw := f.Tag.Get(bound); raw != "" {
					value, err := strconv.ParseInt(raw, 10, 64)
					if err != nil || v.schema["type"] != "integer" {
						panic("invalid numeric contract bound")
					}
					v.schema[bound] = value
				}
			}
			suffix := ""
			if optional {
				suffix = "?"
			} else {
				required = append(required, name)
			}
			parts = append(parts, fmt.Sprintf("%s%s: %s", name, suffix, v.ts))
			properties[name] = v.schema
		}
		return generated{"{ " + strings.Join(parts, "; ") + " }", map[string]any{"type": "object", "properties": properties, "required": required, "additionalProperties": false}}
	default:
		panic("unsupported public contract type: " + t.String())
	}
}
func main() {
	check := flag.Bool("check", false, "Verify generated artifacts are current")
	flag.Parse()
	items := environmentcenter.PublicContracts()
	names := []string{}
	for name := range items {
		names = append(names, name)
	}
	sort.Strings(names)
	ts := "// Code generated by go run ./cmd/center-contracts. DO NOT EDIT.\n"
	definitions := map[string]any{}
	for _, name := range names {
		value := contract(reflect.TypeOf(items[name]))
		ts += "export type " + name + " = " + value.ts + ";\n"
		definitions[name] = value.schema
	}
	schemaRaw, err := json.Marshal(definitions)
	if err != nil {
		panic(err)
	}
	ts += "\nconst schemas = " + string(schemaRaw) + " as const;\n"
	endpointsRaw, err := json.Marshal(environmentcenter.EndpointContracts())
	if err != nil {
		panic(err)
	}
	ts += "export const centerEndpoints = " + string(endpointsRaw) + " as const;\n"
	ts += `
type WireSchema = { type: string; enum?: readonly string[]; minimum?: number; maximum?: number; items?: WireSchema; properties?: Record<string, WireSchema>; required?: readonly string[]; additionalProperties?: boolean | WireSchema };
function matchesWire(value: unknown, schema: WireSchema): boolean {
  if (schema.enum && (typeof value !== 'string' || !schema.enum.includes(value))) return false;
  if (schema.type === 'string' || schema.type === 'boolean') return typeof value === schema.type;
  if (schema.type === 'integer') return typeof value === 'number' && Number.isSafeInteger(value) && (schema.minimum === undefined || value >= schema.minimum) && (schema.maximum === undefined || value <= schema.maximum);
  if (schema.type === 'array') return Array.isArray(value) && value.every(item => matchesWire(item, schema.items!));
  if (schema.type !== 'object' || value === null || typeof value !== 'object' || Array.isArray(value)) return false;
  const record = value as Record<string, unknown>;
  if (schema.required?.some(key => !Object.hasOwn(record, key))) return false;
  return Object.entries(record).every(([key, item]) => {
    const child = schema.properties?.[key];
    if (child) return matchesWire(item, child);
    return typeof schema.additionalProperties === 'object' ? matchesWire(item, schema.additionalProperties) : schema.additionalProperties !== false;
  });
}
export function validateCenterContract(name: keyof typeof schemas, value: unknown): void {
  if (!matchesWire(value, schemas[name] as WireSchema)) throw new Error('CENTER_INVALID_RESPONSE');
}
`
	raw, err := json.MarshalIndent(map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": definitions}, "", "  ")
	if err != nil {
		panic(err)
	}
	for file, content := range map[string][]byte{"internal/envcenter_web/src/contracts.generated.ts": []byte(ts), "internal/environmentcenter/contracts.generated.json": append(raw, '\n')} {
		if *check {
			existing, err := os.ReadFile(file)
			if err != nil || string(existing) != string(content) {
				fmt.Fprintln(os.Stderr, "stale Center contract:", file)
				os.Exit(1)
			}
		} else {
			if err := os.WriteFile(file, content, 0644); err != nil {
				panic(err)
			}
		}
	}
}
