export function resolveContainersLocale(
  languageTag: string | undefined,
): ContainersLocale {
  if (!languageTag) return "en-US";
  const normalized = languageTag.replaceAll("_", "-").toLowerCase();
  const exact = SUPPORTED_CONTAINERS_LOCALES.find(
    (locale) => locale.toLowerCase() === normalized,
  );
  if (exact) return exact;
  const language = normalized.split("-")[0];
  if (language === "zh")
    return normalized.includes("tw") ||
      normalized.includes("hk") ||
      normalized.includes("hant")
      ? "zh-TW"
      : "zh-CN";
  return (
    SUPPORTED_CONTAINERS_LOCALES.find((locale) =>
      locale.toLowerCase().startsWith(`${language}-`),
    ) ?? "en-US"
  );
}

export function containersCopy(
  locale: ContainersLocale,
  key: CopyKey,
  params: CopyParams = {},
): string {
  return CONTAINERS_COPY[locale][key].replace(
    /\{([a-z_]+)\}/giu,
    (placeholder, name: string) =>
      Object.prototype.hasOwnProperty.call(params, name)
        ? String(params[name])
        : placeholder,
  );
}

export function localizedSearchTerms(
  locale: ContainersLocale,
  view: ContainersView,
): readonly string[] {
  return SEARCH_TERMS[locale][view];
}
